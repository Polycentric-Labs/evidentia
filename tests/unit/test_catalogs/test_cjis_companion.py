def test_explicit_generation_is_deterministic_isolated_and_crlf_independent(tmp_path: Path, generator: Any) -> None:
    isolated_source = tmp_path / "source.json"
    isolated_source.write_bytes(SOURCE.read_bytes().replace(b"\r\n", b"\n").replace(b"\n", b"\r\n"))
    output = tmp_path / "output/cjis.json"
    assert generator.main(["--source", str(isolated_source), "--output", str(output)]) == 0
    expected = CATALOG.read_bytes().replace(b"\r\n", b"\n")
    assert output.read_bytes() == expected
    assert b"\r" not in output.read_bytes()
    assert generator.generate(isolated_source, output) == output
    assert output.read_bytes() == expected
    assert sorted(p.relative_to(tmp_path).as_posix() for p in tmp_path.rglob("*.json")) == [
        "output/cjis.json",
        "source.json",
    ]


def test_failed_source_validation_does_not_create_or_overwrite_output(tmp_path: Path, generator: Any) -> None:
    bad = tmp_path / "bad.json"
    bad.write_text('{"schema":"unreviewed"}', encoding="ascii", newline="\n")
    output = tmp_path / "catalog.json"
    with pytest.raises(ValueError):
        generator.generate(bad, output)
    assert not output.exists()
    output.write_text("retained", encoding="ascii", newline="\n")
    with pytest.raises(ValueError):
        generator.generate(bad, output)
    assert output.read_text() == "retained"


def test_import_does_not_write_files(tmp_path: Path) -> None:
    code = (
        "import importlib.util,pathlib; "
        "pathlib.Path.write_text=lambda *a,**k: (_ for _ in ()).throw(AssertionError('import write')); "
        f"s=importlib.util.spec_from_file_location('cjis_no_write',{str(GENERATOR)!r}); "
        "m=importlib.util.module_from_spec(s); s.loader.exec_module(m)"
    )
    subprocess.run([sys.executable, "-B", "-c", code], cwd=tmp_path, check=True, capture_output=True)
    assert not list(tmp_path.iterdir())


@pytest.mark.parametrize("state,expected", [("matching", 0), ("crlf", 0), ("drifted", 1), ("missing", 1)])
def test_check_mode_compares_without_creating_or_changing_files(
    state: str, expected: int, tmp_path: Path, generator: Any, monkeypatch: pytest.MonkeyPatch
) -> None:
    output = tmp_path / "checked.json"
    data = CATALOG.read_bytes().replace(b"\r\n", b"\n")
    if state != "missing":
        output.write_bytes(
            data.replace(b"\n", b"\r\n") if state == "crlf" else b"changed" if state == "drifted" else data
        )
    before = output.read_bytes() if output.exists() else None

    def reject_write(*args: Any, **kwargs: Any) -> None:
        raise AssertionError("--check must not write")

    monkeypatch.setattr(Path, "write_text", reject_write)
    monkeypatch.setattr(Path, "write_bytes", reject_write)
    assert generator.main(["--source", str(SOURCE), "--output", str(output), "--check"]) == expected
    assert (output.read_bytes() if output.exists() else None) == before


@pytest.mark.parametrize("alias", ["same-path", "hard-link"])
def test_generation_never_overwrites_source_through_file_aliases(alias: str, tmp_path: Path, generator: Any) -> None:
    source = tmp_path / "source.json"
    source.write_bytes(SOURCE.read_bytes())
    output = source
    if alias == "hard-link":
        output = tmp_path / "alias.json"
        output.hardlink_to(source)
        assert output.samefile(source)
    original = source.read_bytes()
    with pytest.raises(ValueError, match="same file"):
        generator.generate(source, output)
    assert source.read_bytes() == output.read_bytes() == original
