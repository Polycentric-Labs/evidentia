def _rows(payload: dict[str, Any]) -> dict[int, dict[str, Any]]:
    records = [row for control in payload["controls"] for row in control["source_rows"]]
    assert len(records) == len({r["row"] for r in records}) == 1533
    assert [r["row"] for r in records] == sorted(r["row"] for r in records)
    return {r["row"]: r for r in records}


def _physical_rows(records: dict[int, dict[str, Any]]) -> list[Any]:
    result = []
    for number, row in records.items():
        labels = {col: label for label, col in json.loads(row["provenance"]["columns"]).items()}
        metadata = json.loads(row["provenance"]["cell_metadata"])
        result.append([number, [[c, row["values"][labels[c]], *metadata[c]] for c in COLUMNS]])
    return result


def test_every_source_cell_type_and_format_matches_the_independent_workbook_contract(
    projection: dict[str, Any], payload: dict[str, Any]
) -> None:
    source_tuples = [[r["row"], [[c, *r["cells"][c]] for c in COLUMNS]] for r in projection["rows"]]
    assert _digest(source_tuples) == PHYSICAL_ROWS_SHA256
    retained = _physical_rows(_rows(payload))
    assert _digest(retained) == PHYSICAL_ROWS_SHA256
    assert retained == source_tuples
    assert sum(len(r[1]) for r in retained) == 38325
    assert projection["cell_fields"][3] == "xml_style_id"
    assert projection["headers"][0]["cells"]["X"][3] == 91
    assert projection["xml_cell_styles"][91]["attributes"]["numFmtId"] == "0"
    assert all(row["kind"] == "fragment" and row["sheet"] == "v6.1" for row in _rows(payload).values())
    assert {row["source_sha256"] for row in _rows(payload).values()} == {projection["source_sha256"]}


def test_every_location_and_merge_anchor_matches_independently_reviewed_expectations(payload: dict[str, Any]) -> None:
    associations = []
    merges = []
    for number, row in _rows(payload).items():
        provenance = row["provenance"]
        associations.append([number, provenance["source_location"], provenance["reference_unit"]])
        labels = {col: label for label, col in json.loads(provenance["columns"]).items()}
        metadata = []
        for col in COLUMNS:
            label = labels[col]
            if label in row["resolved_values"]:
                metadata.append(
                    [
                        col,
                        provenance[f"{label}.anchor"],
                        provenance[f"{label}.merged_range"],
                        row["resolved_values"][label],
                    ]
                )
        merges.append([number, metadata])
    assert _digest(associations) == ASSOCIATION_SHA256
    assert _digest(merges) == MERGES_SHA256


def test_bundled_output_and_native_reload_preserve_all_source_tuples(payload: dict[str, Any]) -> None:
    assert json.loads(CATALOG.read_text(encoding="utf-8")) == payload
    catalog = load_evidentia_catalog(CATALOG)
    loaded = catalog.model_dump(mode="json")
    assert _digest(_physical_rows(_rows(loaded))) == PHYSICAL_ROWS_SHA256
    assert catalog.control_count == 324
    assert len(catalog.statement_rows()) == 324
    assert len(catalog.families) == 27
    assert Counter(c.properties["source_unit_kind"] for c in catalog.controls) == {
        "control": 176,
        "enhancement": 118,
        "section": 30,
    }
    source_free = copy.deepcopy(payload)
    for control in source_free["controls"]:
        control["source_rows"] = []
    without_rows = ControlCatalog.model_validate(source_free)
    analyzer = GapAnalyzer()
    assert list(analyzer._build_required_set({catalog.framework_id: catalog})) == list(
        analyzer._build_required_set({without_rows.framework_id: without_rows})
    )
    assert catalog.statement_rows() == without_rows.statement_rows()
    assert catalog.text_depth == without_rows.text_depth


