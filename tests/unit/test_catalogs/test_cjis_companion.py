PHYSICAL_ROWS_SHA256 = "e65059be26c05ac0fcccb164b741c881b17aa7935436d22eae76b2b568f78bb9"
ASSOCIATION_SHA256 = "4ef8b5d66138cbe3af279d1138c8411f84701139d4758212277530a23d2dbae8"
