@pytest.mark.parametrize(
    "case",
    [
        "hash",
        "size",
        "schema",
        "version",
        "date",
        "sheet",
        "shape",
        "columns",
        "header",
        "cloud-leaf",
        "cloud-parent",
        "duplicate-row",
        "bool-row",
        "missing-row",
        "reorder-row",
        "duplicate-id",
        "normalized-collision",
        "double-assignment",
        "at3-blank",
        "at3-merge",
        "numeric-value",
        "numeric-format",
        "numeric-merge",
        "title-csa",
        "title-sa",
        "source-difference",
        "clause-group",
        "cell-loss",
        "arbitrary-cell",
        "nonfinite",
    ],
)
def test_unreviewed_source_changes_fail_closed(case: str, projection: dict[str, Any], generator: Any) -> None:
    data = copy.deepcopy(projection)
    rows = {r["row"]: r for r in data["rows"]}
    if case in {"hash", "size", "schema", "version", "date", "sheet", "shape", "columns"}:
        key, value = {
            "hash": ("source_sha256", "0" * 64),
            "size": ("source_bytes", 1),
            "schema": ("schema", "next"),
            "version": ("version", "6.2"),
            "date": ("published_on", "2026-07-23"),
            "sheet": ("sheet", "next"),
            "shape": ("dimensions", [1557, 25]),
            "columns": ("columns", list(reversed(COLUMNS))),
        }[case]
        data[key] = value
    elif case == "header":
        data["headers"][0]["cells"]["R"][0] = "Title"
    elif case == "cloud-leaf":
        data["headers"][1]["cells"]["X"][0] = "SaaS"
    elif case in {"cloud-parent", "at3-merge", "numeric-merge"}:
        data["merges"].remove({"cloud-parent": "W1:Y1", "at3-merge": "R233:R264", "numeric-merge": "R1461:R1463"}[case])
    elif case == "duplicate-row":
        data["rows"][1] = data["rows"][0]
    elif case == "bool-row":
        data["rows"][0]["row"] = True
    elif case == "missing-row":
        data["rows"].pop()
    elif case == "reorder-row":
        data["rows"][0], data["rows"][1] = data["rows"][1], data["rows"][0]
    elif case in {"duplicate-id", "normalized-collision"}:
        data["locations"][1]["id"] = (
            data["locations"][0]["id"] if case == "duplicate-id" else " " + data["locations"][0]["id"].lower() + " "
        )
    elif case == "double-assignment":
        data["locations"][1]["rows"].append(data["locations"][0]["rows"][0])
    elif case == "at3-blank":
        rows[233]["cells"]["R"][0] = "AT-4"
    elif case in {"numeric-value", "numeric-format"}:
        rows[1461]["cells"]["R"][0 if case == "numeric-value" else 2] = "5.20" if case == "numeric-value" else "General"
    elif case in {"title-csa", "title-sa"}:
        rows[40 if case == "title-csa" else 1312]["cells"]["S"][0] = "changed"
    elif case == "source-difference":
        rows[1514]["cells"]["T"][0] = "changed"
    elif case == "clause-group":
        next(s for s in data["reviewed_scopes"] if s["location"] == "3.2.2(1)")["reference_unit"] = "3.2.2(1)"
    elif case == "cell-loss":
        del rows[4]["cells"]["B"]
    elif case == "arbitrary-cell":
        rows[83]["cells"]["W"][0] = "Both"
    elif case == "nonfinite":
        rows[4]["cells"]["B"][0] = float("nan")
    with pytest.raises(ValueError):
        generator.build_catalog(data)


